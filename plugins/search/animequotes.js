import axios from 'axios';

const handler = async (m, { text, usedPrefix, command, reply }) => {
	reply(global.mess?.wait || '⏳ Mengambil quotes anime...');

	try {
		const apiUrl = global.API('kyzz', '/api/search/animequotes', { query: text ? text.trim() : 'naruto' }, 'apikey');
		const { data } = await axios.get(apiUrl, { timeout: 25000 });

		const list = data.result || data.data || [];
		if (!Array.isArray(list) || list.length === 0) {
			return reply(`❌ Quotes untuk "*${text}*" tidak ditemukan.`);
		}

		let out = `🌸 *QUOTES TOKOH ANIME* 🌸\n\n`;
		list.slice(0, 5).forEach((q, idx) => {
			out += `*${idx + 1}. ${q.character || q.tokoh || 'Tokoh'}* (${q.anime || '-'})` + '\n';
			out += `💬 _"${q.quote || q.quotes || q.kata || '-'}"_\n\n`;
		});

		return reply(out.trim());
	} catch (e) {
		console.error('[ANIME QUOTES SEARCH ERROR]', e.message);
		return reply(`❌ Gagal memuat quotes anime: ${e.message}`);
	}
};

handler.help = ['animequotes [anime/tokoh]'];
handler.tags = ['search'];
handler.command = ['animequotes', 'carianimequotes'];
handler.limit = true;
handler.register = true;

export default handler;
