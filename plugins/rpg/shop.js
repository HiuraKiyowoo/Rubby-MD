import databaseApi from '../../lib/database.js'
import { formatCurrency, getCleanNumber } from '../../lib/economy.js'

let handler = async (m, { usedPrefix }) => {
  const senderNumber = getCleanNumber(m.sender)
  const user = databaseApi.getUser(senderNumber)
  const packages = global.settings?.shop?.limitPackages || []

  let caption = `╭━━━〔 ୨ৎ 🛒 *TOKO LIMIT RUBBY* ୨ৎ 〕━━━╮\n┇\n`
  caption += `┇ 👤 *Pembeli* : ${user?.name || m.pushName || 'Pengguna'}\n`
  caption += `┇ 💵 *Saldo*   : ${formatCurrency(user?.balance || 0)}\n┇\n`
  caption += `┇ 📦 *DAFTAR PAKET LIMIT TERSEDIA:*\n`

  for (const pkg of packages) {
    caption += `┇ [ID: ${pkg.id}] *${pkg.name}*\n`
    caption += `┇ ├ 🎟️ Jumlah : +${pkg.amount} Limit\n`
    caption += `┇ └ 💵 Harga  : ${formatCurrency(pkg.price)}\n`
  }

  caption += `┇\n┇ 💡 *CARA MEMBELI:*\n`
  caption += `┇ Ketik: *${usedPrefix}buylimit <id_paket>*\n`
  caption += `┇ Contoh: *${usedPrefix}buylimit 2* (Beli Paket Sedang)\n`
  caption += `╰━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━╯`

  await m.reply(caption.trim())
}

handler.help = ['shop', 'toko']
handler.tags = ['rpg']
handler.command = ['shop', 'toko']

export default handler
