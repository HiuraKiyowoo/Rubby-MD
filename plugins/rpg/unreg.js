import databaseApi from '../../lib/database.js'
import { getCleanNumber } from '../../lib/economy.js'

let handler = async (m, { text, usedPrefix }) => {
  const senderNumber = getCleanNumber(m.sender)
  const user = databaseApi.getUser(senderNumber)

  if (!user || user.registered !== 1) {
    return m.reply('❌ Kamu belum terdaftar dalam sistem bot.')
  }

  if (text.trim().toLowerCase() !== 'confirm') {
    return m.reply(`⚠️ *PERINGATAN PEMBATALAN REGISTRASI*\n\nJika kamu membatalkan registrasi, status akunmu akan dinonaktifkan.\nUntuk melanjutkan, ketik:\n👉 *${usedPrefix}unreg confirm*`)
  }

  const res = databaseApi.unregUser(senderNumber)
  if (res.success) {
    await m.reply(`✅ Akun *${user.name || senderNumber}* berhasil di-unreg.\nKamu dapat mendaftar kembali kapan saja menggunakan *${usedPrefix}daftar*.`)
  } else {
    await m.reply('❌ Gagal membatalkan registrasi akun.')
  }
}

handler.help = ['unreg']
handler.tags = ['rpg']
handler.command = ['unreg']

export default handler
