import databaseApi from '../../lib/database.js'

const handler = async (m) => {
  const user = databaseApi.getUser(m.sender)
  user.rpg = user.rpg || {}
  if (!user.rpg.pet) {
    return m.reply('🐾 Kamu belum memiliki pet! Ketik *.adoptthepet kucing* atau *anjing* untuk mengadopsi pet barumu.')
  }
  const p = user.rpg.pet
  await m.reply(`🐾 *STATUS PET COMPANION*\n\n📛 Nama : *${p.name}*\n🏷️ Jenis : *${p.type}*\n⭐ Level : *${p.level || 1}*\n🍖 Lapar : *${p.hunger || 100}%*\n❤️ Nyawa : *${p.hp || 100}%*\n\nJangan lupa beri makan dengan *.feed* yaa! ♡`)
}
handler.help = ['pet', 'adoptthepet <jenis>']
handler.tags = ['rpg']
handler.command = ['pet', 'adoptthepet']
handler.register = true
export default handler
