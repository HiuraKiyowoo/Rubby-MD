import databaseApi from '../../lib/database.js'

const handler = async (m, { text }) => {
  const user = databaseApi.getUser(m.sender)
  user.rpg = user.rpg || {}
  if (!text) {
    const current = user.rpg.guild || 'Belum bergabung dengan Guild manapun'
    return m.reply(`🏰 *GUILD PETUALANG*\n\nGuild Kamu: *${current}*\n\nKetik *.guild <nama_guild>* untuk mendirikan atau bergabung dengan Guild.`)
  }
  user.rpg.guild = text.trim()
  databaseApi.save()
  await m.reply(`✓ Kamu resmi terdaftar sebagai anggota Guild: *${text.trim()}*! 🛡️`)
}
handler.help = ['guild [nama_guild]']
handler.tags = ['rpg']
handler.command = ['guild']
handler.register = true
export default handler
