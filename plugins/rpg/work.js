import databaseApi from '../../lib/database.js'
import Economy, { formatCurrency, formatDuration, getCleanNumber } from '../../lib/economy.js'

let handler = async (m, { usedPrefix }) => {
  const senderNumber = getCleanNumber(m.sender)
  const user = databaseApi.getUser(senderNumber)

  if (!user || user.registered !== 1) {
    return m.reply(`🌸 Kamu belum terdaftar!\nKetik *${usedPrefix}daftar <nama>* untuk mendaftar terlebih dahulu.`)
  }

  const workRes = Economy.work(senderNumber)

  if (!workRes.success) {
    if (workRes.reason === 'cooldown') {
      return m.reply(`⏳ Kamu masih kelelahan sehabis bekerja!\nIstirahat dulu selama *${formatDuration(workRes.remainingMs)}* sebelum bekerja kembali.`)
    }
    return m.reply('❌ Gagal melakukan pekerjaan.')
  }

  const caption = `╭━━━〔 ୨ৎ 💼 *HASIL KERJA KERAS* ୨ৎ 〕━━━╮
┇
┇ 👷 *Profesi*  : ${workRes.job}
┇ 📋 *Tugas*    : ${workRes.task}
┇
┇ 💵 *Gaji*     : +${formatCurrency(workRes.pay)}
┇ ✨ *EXP*      : +${workRes.expGain} EXP
┇ 💰 *Sisa Saldo* : ${formatCurrency(workRes.newBalance)}
┇
╰━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━╯`

  await m.reply(caption.trim())
}

handler.help = ['work', 'kerja']
handler.tags = ['rpg']
handler.command = ['work', 'kerja']

export default handler
