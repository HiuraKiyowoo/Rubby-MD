import databaseApi from '../../lib/database.js'
import { ACHIEVEMENTS_CONFIG } from '../../lib/rpg.js'
import { getCleanNumber } from '../../lib/economy.js'

let handler = async (m, { usedPrefix }) => {
  const senderNumber = getCleanNumber(m.sender)
  const user = databaseApi.getUser(senderNumber)

  if (!user || user.registered !== 1) {
    return m.reply(`🌸 Kamu belum terdaftar!\nKetik *${usedPrefix}daftar <nama>* untuk mendaftar terlebih dahulu.`)
  }

  const unlocked = databaseApi.getAchievements(senderNumber)
  const unlockedSet = new Set(unlocked.map(a => a.achievement_id))

  let text = `╭━━━〔 ୨ৎ 🏆 *PIALA & PENCAPAIAN* ୨ৎ 〕━━━╮\n┇\n`
  text += `┇ 👤 *Pemain* : ${user.name || m.pushName || 'Player'}\n`
  text += `┇ 🎖️ *Total*  : ${unlocked.length} / ${ACHIEVEMENTS_CONFIG.length} Terbuka\n┇\n`

  for (const ach of ACHIEVEMENTS_CONFIG) {
    const isUnlocked = unlockedSet.has(ach.id)
    const icon = isUnlocked ? '🏆 [TERBUKA]' : '🔒 [TERKUNCI]'
    text += `┇ ${icon} *${ach.title}*\n`
    text += `┇ └ _${ach.desc}_\n`
  }

  text += `┇\n╰━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━╯`

  await m.reply(text.trim())
}

handler.help = ['achievements', 'piala']
handler.tags = ['rpg']
handler.command = ['achievements', 'piala']

export default handler
