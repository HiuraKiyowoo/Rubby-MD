import databaseApi from '../../lib/database.js'

const handler = async (m) => {
  const user = databaseApi.getUser(m.sender)
  user.rpg = user.rpg || {}
  user.rpg.inventory = user.rpg.inventory || {}
  const ikan = user.rpg.inventory.ikan || 0
  if (ikan < 2) return m.reply('Bahan belum cukup! Kamu membutuhkan minimal 2 ekor ikan untuk memasak Sup Ikan.')
  user.rpg.inventory.ikan -= 2
  user.rpg.inventory.makanan = (user.rpg.inventory.makanan || 0) + 1
  databaseApi.save()
  await m.reply('🍲 *DAPUR MEMASAK*\n\nBerhasil memasak 1 Porsi Sup Ikan Hangat! Gunakan untuk memulihkan energi petualangan.')
}
handler.help = ['cook']
handler.tags = ['rpg']
handler.command = ['cook', 'cooking']
handler.register = true
export default handler
