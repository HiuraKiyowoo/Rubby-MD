import databaseApi from '../../lib/database.js'

const handler = async (m) => {
  const user = databaseApi.getUser(m.sender)
  user.rpg = user.rpg || {}
  user.rpg.equipment = user.rpg.equipment || {}
  const weaponLvl = user.rpg.equipment.weaponLevel || 1
  const cost = weaponLvl * 10000
  const ironNeed = weaponLvl * 5
  user.rpg.inventory = user.rpg.inventory || {}
  const iron = user.rpg.inventory.besi || 0

  if ((user.money || 0) < cost || iron < ironNeed) {
    return m.reply(`⚒️ *BLACKSMITH FORGE*\n\nUntuk upgrade Senjata ke Level ${weaponLvl + 1}:\n💰 Biaya: *Rp ${cost.toLocaleString()}*\n⚙️ Besi: *${iron}/${ironNeed}*\n\nUang atau bahanmu belum cukup!`)
  }
  user.money -= cost
  user.rpg.inventory.besi -= ironNeed
  user.rpg.equipment.weaponLevel = weaponLvl + 1
  databaseApi.save()
  await m.reply(`✓ Berhasil menempa senjata ke Level *${weaponLvl + 1}*! Seranganmu semakin tajam. ⚔️`)
}
handler.help = ['blacksmith']
handler.tags = ['rpg']
handler.command = ['blacksmith', 'tempaarmor']
handler.register = true
export default handler
