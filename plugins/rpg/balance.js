import databaseApi from '../../lib/database.js'
import { formatCurrency, getCleanNumber } from '../../lib/economy.js'

let handler = async (m, { usedPrefix }) => {
  const senderNumber = getCleanNumber(m.sender)
  const user = databaseApi.getUser(senderNumber)

  if (!user || user.registered !== 1) {
    return m.reply(`🌸 Kamu belum terdaftar!\nKetik *${usedPrefix}daftar <nama>* untuk membuat dompet dan mendapatkan modal awal.`)
  }

  const caption = `╭━━━〔 ୨ৎ 💰 *DOMPET DIGITAL* ୨ৎ 〕━━━╮
┇
┇ 👤 *Pemilik*     : ${user.name || m.pushName || 'Pengguna'}
┇ 💵 *Saldo Aktif* : ${formatCurrency(user.balance)}
┇ 📈 *Total Cari*  : ${formatCurrency(user.total_earned)}
┇ 📉 *Total Belanja*: ${formatCurrency(user.total_spent)}
┇
┇ 💡 *TIPS EKONOMI:*
┇ ├ Bekerja untuk uang: *${usedPrefix}work*
┇ ├ Klaim gaji harian: *${usedPrefix}daily*
┇ ├ Transfer sesama pengguna: *${usedPrefix}transfer <@user> <jumlah>*
┇ └ Belanja paket limit di *${usedPrefix}shop*
┇
╰━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━╯`

  await m.reply(caption.trim())
}

handler.help = ['balance', 'saldo']
handler.tags = ['rpg']
handler.command = ['balance', 'saldo']

export default handler
