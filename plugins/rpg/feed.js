import databaseApi from '../../lib/database.js'

const handler = async (m) => {
  const user = databaseApi.getUser(m.sender)
  user.rpg = user.rpg || {}
  if (!user.rpg.pet) return m.reply('Kamu belum punya hewan peliharaan! Adopsi dulu dengan *.adoptthepet*')
  user.rpg.inventory = user.rpg.inventory || {}
  const ikan = user.rpg.inventory.ikan || 0
  if (ikan < 1) return m.reply('Kamu tidak memiliki ikan untuk makanan pet! Dapatkan dengan *.fishing*.')
  user.rpg.inventory.ikan -= 1
  user.rpg.pet.hunger = 100
  user.rpg.pet.level = (user.rpg.pet.level || 1) + 1
  databaseApi.save()
  await m.reply(`✓ Berhasil memberi makan ${user.rpg.pet.name}! Tingkat kenyang pulih ke 100% dan level naik ke Level ${user.rpg.pet.level}. 🐾♡`)
}
handler.help = ['feed']
handler.tags = ['rpg']
handler.command = ['feed', 'feedpet']
handler.register = true
export default handler
