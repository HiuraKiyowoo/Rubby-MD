const handler = async (m, { text }) => {
  const num = (text || m.quoted?.sender || '').replace(/[^0-9]/g, '')
  if (!num) return m.reply('Nomor target tidak valid! Contoh: *.delowner 628xxx*')
  const idx = global.owner.indexOf(num)
  if (idx !== -1) {
    global.owner.splice(idx, 1)
    return m.reply(`✓ Berhasil menghapus @${num} dari daftar Owner.`, null, { mentions: [`${num}@s.whatsapp.net`] })
  }
  await m.reply('Nomor tersebut bukan owner!')
}
handler.help = ['delowner <nomor/@tag>']
handler.tags = ['owner']
handler.command = ['delowner']
handler.owner = true
export default handler
