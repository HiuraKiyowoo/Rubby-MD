import databaseApi from '../../lib/database.js'

const handler = async (m, { text }) => {
  const num = (text || m.quoted?.sender || '').replace(/[^0-9]/g, '')
  if (!num) return m.reply('Tag atau sebutkan nomor target! Contoh: *.unbanuser 628xxx*')
  const jid = `${num}@s.whatsapp.net`
  const user = databaseApi.getUser(jid)
  user.banned = false
  databaseApi.save()
  await m.reply(`✓ Pengguna @${num} berhasil di-unban.`, null, { mentions: [jid] })
}
handler.help = ['unbanuser <nomor/@tag>']
handler.tags = ['owner']
handler.command = ['unbanuser', 'unban']
handler.owner = true
export default handler
