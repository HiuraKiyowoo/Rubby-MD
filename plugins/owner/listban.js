import databaseApi from '../../lib/database.js'

const handler = async (m) => {
  const db = databaseApi.get()
  const bannedUsers = Object.entries(db.users || {}).filter(([_, u]) => u.banned).map(([jid]) => jid.split('@')[0])
  if (bannedUsers.length === 0) return m.reply('Tidak ada pengguna yang sedang dibanned.')
  const list = bannedUsers.map((n, i) => `${i + 1}. @${n}`).join('\n')
  await m.reply(`🚫 *DAFTAR PENGGUNA TERBANNED*\n\n${list}`, null, { mentions: bannedUsers.map(n => `${n}@s.whatsapp.net`) })
}
handler.help = ['listban']
handler.tags = ['owner']
handler.command = ['listban', 'banlist']
handler.owner = true
export default handler
