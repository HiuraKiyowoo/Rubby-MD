import databaseApi from '../../lib/database.js'

const handler = async (m) => {
  const chat = databaseApi.getChat(m.chat)
  chat.isBanned = false
  databaseApi.save()
  await m.reply('✓ Chat ini berhasil di-unban, bot akan merespon kembali.')
}
handler.help = ['unbanchat']
handler.tags = ['owner']
handler.command = ['unbanchat', 'unmutechat']
handler.owner = true
export default handler
